#!/usr/bin/env python3
"""Rasterize a PNG into a palette-indexed RGB565 sprite for a pixelitl face.

Usage:
    python3 rasterize_sprite.py INPUT.png OUTPUT.h [--size 48] [--name dota_sprite] [--palette 16]

- Resizes INPUT to SIZE×SIZE (preserving aspect, padded transparent).
- Quantizes to a palette of up to --palette colors; reserves index 0 for transparent.
- Writes a C header with DOTA_SPRITE_W/H, DOTA_PAL[], DOTA_SPRITE[].
  (The identifier prefix is taken from --name, so --name foo → FOO_SPRITE_W etc.)

Sprite is 1 byte per pixel, row-major. Draw with a masked blit (skip index 0).

Requires: Pillow. Install:   python3 -m venv v && v/bin/pip install Pillow
Run inside the venv:         v/bin/python rasterize_sprite.py ...
"""
import argparse, os, sys
from PIL import Image

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("output")
    ap.add_argument("--size", type=int, default=48)
    ap.add_argument("--name", default="sprite")
    ap.add_argument("--palette", type=int, default=16,
                    help="Max palette colors (including transparent). 4..32 reasonable.")
    ap.add_argument("--alpha-threshold", type=int, default=128,
                    help="Pixels with alpha below this become transparent.")
    args = ap.parse_args()

    prefix = args.name.upper()
    size = args.size
    max_pal = max(2, args.palette)

    src = Image.open(args.input).convert("RGBA")
    # Fit into a square, preserving aspect, padded transparent
    sw, sh = src.size
    scale = size / max(sw, sh)
    new_w, new_h = max(1, int(sw * scale)), max(1, int(sh * scale))
    resized = src.resize((new_w, new_h), Image.LANCZOS)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.paste(resized, ((size - new_w) // 2, (size - new_h) // 2), resized)

    # Split alpha — treat low-alpha as transparent, keep RGB for quantization
    rgb = Image.new("RGB", (size, size), (0, 0, 0))
    rgb.paste(canvas, mask=canvas.split()[3])
    alpha = canvas.split()[3]

    # Quantize opaque pixels only (mask out transparent before quantize)
    # Build an RGB-only image of opaque pixels for palette fitting
    opaque_pixels = []
    for y in range(size):
        for x in range(size):
            if alpha.getpixel((x, y)) >= args.alpha_threshold:
                opaque_pixels.append(rgb.getpixel((x, y)))
    if not opaque_pixels:
        print("No opaque pixels after threshold.", file=sys.stderr)
        sys.exit(1)

    # Use Pillow's quantize on a dummy image of the opaque pixels
    qhelper = Image.new("RGB", (len(opaque_pixels), 1))
    qhelper.putdata(opaque_pixels)
    qhelper = qhelper.quantize(colors=max_pal - 1, method=Image.MEDIANCUT)
    q_pal = qhelper.getpalette()[: (max_pal - 1) * 3]
    # Build the final palette: index 0 = transparent sentinel (0,0,0,0), rest = colors
    palette = [(0, 0, 0, 0)]
    for i in range(max_pal - 1):
        if i * 3 + 2 < len(q_pal):
            palette.append((q_pal[i * 3], q_pal[i * 3 + 1], q_pal[i * 3 + 2], 255))

    # Quantize the whole rgb image against the selected palette (nearest neighbor)
    def nearest(r, g, b):
        best, best_d = 1, 10 ** 9
        for i in range(1, len(palette)):
            pr, pg, pb, _ = palette[i]
            d = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2
            if d < best_d:
                best, best_d = i, d
        return best

    indices = [[0] * size for _ in range(size)]
    for y in range(size):
        for x in range(size):
            if alpha.getpixel((x, y)) < args.alpha_threshold:
                indices[y][x] = 0
            else:
                r, g, b = rgb.getpixel((x, y))
                indices[y][x] = nearest(r, g, b)

    # Emit header
    lines = []
    lines.append(f"// Auto-generated by tools/rasterize_sprite.py from {os.path.basename(args.input)}")
    lines.append(f"// Size: {size}x{size}  Palette: {len(palette)} entries (0 = transparent)")
    lines.append("#pragma once\n")
    lines.append(f"#define {prefix}_W {size}")
    lines.append(f"#define {prefix}_H {size}\n")

    # Palette as static const array of RGB565 values
    def rgb565(r, g, b):
        return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

    lines.append(f"static const unsigned short {prefix}_PAL[{len(palette)}] = {{")
    for i, (r, g, b, a) in enumerate(palette):
        if a == 0:
            lines.append(f"    0x0000,  // {i}: transparent")
        else:
            lines.append(f"    0x{rgb565(r, g, b):04X},  // {i}: rgb({r},{g},{b})")
    lines.append("};\n")

    lines.append(f"static const unsigned char {prefix}_DATA[{prefix}_W * {prefix}_H] = {{")
    for y in range(size):
        row = ", ".join(f"{v:2d}" for v in indices[y])
        lines.append(f"    {row},")
    lines.append("};\n")

    with open(args.output, "w") as f:
        f.write("\n".join(lines))
    print(f"Wrote {args.output} ({size}x{size}, {len(palette)} palette entries)")

if __name__ == "__main__":
    main()
